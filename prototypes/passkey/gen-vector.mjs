// Gate 1: drive a REAL browser WebAuthn flow with Chrome's virtual authenticator and write the result as a Solidity test vector.
// The browser, not our code, produces the authenticator data, client data JSON and the P-256 signature.
//   node gen-vector.mjs > ../../contracts/test/WebAuthnVector.sol
import puppeteer from "puppeteer-core";
import http from "node:http";
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url)), PORT = Number(process.env.PORT || 8093);
const chrome = ["/usr/bin/google-chrome", "/usr/bin/chromium", "/usr/bin/chromium-browser"].find(p => fs.existsSync(p));
const server = http.createServer((q, r) => { r.setHeader("content-type", "text/html"); r.end(fs.readFileSync(path.join(dir, "proto.html"))); }).listen(PORT, "127.0.0.1");
const b = await puppeteer.launch({ executablePath: chrome, args: ["--no-sandbox"] }), p = await b.newPage();
const cdp = await p.target().createCDPSession();
await cdp.send("WebAuthn.enable");
await cdp.send("WebAuthn.addVirtualAuthenticator", { options: { protocol: "ctap2", transport: "internal", hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
await p.goto(`http://localhost:${PORT}/`);
const challenge = "0x" + crypto.createHash("sha256").update("lgtie gate 1 challenge").digest("hex");
const cred = await p.evaluate(() => window.pk.enroll("maya"));
const sig = await p.evaluate((c, id) => window.pk.sign(c, id), challenge.slice(2), cred.credentialId);
await b.close(); server.close();

const cd = sig.clientDataJSON, idx = s => cd.indexOf(s);
const b64url = Buffer.from(challenge.slice(2), "hex").toString("base64url");
if (idx('"challenge":"' + b64url + '"') < 0 || idx('"type":"webauthn.get"') < 0) throw new Error("client data does not contain the expected challenge/type: " + cd);
const rpIdHash = "0x" + crypto.createHash("sha256").update(cred.rpId).digest("hex");
const esc = s => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
console.log(`// SPDX-License-Identifier: MIT
pragma solidity 0.8.24;

// GENERATED by prototypes/passkey/gen-vector.mjs from a real Chrome virtual-authenticator run. Do not edit by hand.
library WebAuthnVector {
    bytes32 constant CHALLENGE = ${challenge};
    bytes32 constant RP_ID_HASH = ${rpIdHash};       // sha256("${cred.rpId}")
    uint256 constant X = 0x${cred.x};
    uint256 constant Y = 0x${cred.y};
    uint256 constant R = 0x${sig.r};
    uint256 constant S = 0x${sig.s};
    bytes constant AUTH_DATA = hex"${sig.authenticatorData}";
    string constant CLIENT_DATA_JSON = "${esc(cd)}";
    uint256 constant TYPE_INDEX = ${idx('"type":"webauthn.get"')};
    uint256 constant CHALLENGE_INDEX = ${idx('"challenge":"')};
}`);
console.error("credentialId:", cred.credentialId, "| rpId:", cred.rpId, "| clientDataJSON:", cd);

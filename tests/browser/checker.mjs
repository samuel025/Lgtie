await p.screenshot({path: process.env.SHOT || "/tmp/tb-mobile.png"});
ok("no page errors", errs.length === 0, errs.join(" | "));
await b.close(); console.log(fails ? fails + " FAILED" : "all passed"); process.exit(fails ? 1 : 0);

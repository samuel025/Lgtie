import puppeteer from "puppeteer-core";
import fs from "node:fs";
const BASE = process.env.BASE || "http://localhost:8090/index.html";
const chrome = ["/usr/bin/google-chrome", "/usr/bin/chromium", "/usr/bin/chromium-browser", "/snap/bin/chromium"].find(p => fs.existsSync(p));
const b = await puppeteer.launch({executablePath: chrome, args: ["--no-sandbox"]});
const p = await b.newPage(); const errs = []; p.on("pageerror", e => errs.push("pageerror: " + e.message)); p.on("console", m => { if (m.type() === "error") errs.push("console: " + m.text()); });
let fails = 0; const ok = (n, c, x = "") => { console.log((c ? "ok   " : "FAIL ") + n + (c ? "" : " " + x)); if (!c) fails++; };
const T = sel => p.$eval(sel, e => e.innerText).catch(() => "");
await p.setViewport({width: 1000, height: 900});
await p.goto(BASE); await new Promise(r => setTimeout(r, 300));
ok("home headline", /Know if you are covered/.test(await T("h1")), await T("h1"));
await p.goto(BASE + "#check/warranty"); await new Promise(r => setTimeout(r, 300));
ok("warranty page has 7 questions", (await p.$$(".q")).length === 7);
for (let i = 0; i < 7; i++) await p.evaluate(i => document.querySelectorAll(".q")[i].querySelector('button[data-v="1"]').click(), i);
await new Promise(r => setTimeout(r, 300));
ok("all yes -> Covered", /Covered/.test(await T(".res .big")) && !/Not covered/.test(await T(".res .big")), await T(".res .big"));
for (let i = 0; i < 20 && /Checking/.test(await T("#vbadge")); i++) await new Promise(r => setTimeout(r, 500));
ok("all yes is confirmed by the processor on X Layer", /Confirmed by the TapeOut processor/.test(await T("#vbadge")), await T("#vbadge"));
await p.evaluate(() => document.querySelectorAll(".q")[4].querySelector('button[data-v="0"]').click());
await new Promise(r => setTimeout(r, 300));
for (let i = 0; i < 20 && /Checking/.test(await T("#vbadge")); i++) await new Promise(r => setTimeout(r, 500));
ok("Q5 no -> Not covered with the excluded-cause reason", /Not covered/.test(await T(".res .big")) && /excluded cause/.test(await T(".res .why")), await T(".res"));
ok("Q5 no is also confirmed on chain", /Confirmed by the TapeOut processor/.test(await T("#vbadge")), await T("#vbadge"));
const hashNow = await p.evaluate(() => location.hash);
ok("answers are in the link (a=...)", /a=\d+/.test(hashNow), hashNow);
await p.goto(BASE + "#check/warranty/a=111"); await new Promise(r => setTimeout(r, 300));
ok("a shared link restores the result", /Not covered/.test(await T(".res .big")), await T(".res .big"));
await p.goto(BASE + "#check/bounty"); await new Promise(r => setTimeout(r, 300));
ok("bounty page has 8 questions", (await p.$$(".q")).length === 8);
await p.goto(BASE + "#build"); await new Promise(r => setTimeout(r, 600));
ok("build shows circuit matches rules", /same answer as your rules/.test(await T("#out")), (await T("#out")).slice(0, 200));
await p.click("#tabt"); await new Promise(r => setTimeout(r, 300));
await p.evaluate(() => { const t = document.querySelector("#src"); t.value = "name: x\nquestion: a?\nrule: nonsense"; t.dispatchEvent(new Event("input")); });
await new Promise(r => setTimeout(r, 600));
ok("build reports errors with line numbers", /Line 3/.test(await T("#out")) || /Fix these first/.test(await T("#out")), await T("#out"));
await p.goto(BASE + "#verify"); await new Promise(r => setTimeout(r, 300));
ok("verify page renders", /Verify a published circuit/.test(await T("h1")));
await p.goto(BASE + "#about"); await new Promise(r => setTimeout(r, 300));
ok("about page renders the honesty note", /does not check that the answers are true/.test(await T("main")));
await p.goto(BASE + "#check/nonsense"); await new Promise(r => setTimeout(r, 300));
ok("unknown checker shows a friendly message", /could not open that checker/.test(await T("h1")));
await p.setViewport({width: 375, height: 800}); await p.goto(BASE + "#check/warranty"); await new Promise(r => setTimeout(r, 300));
